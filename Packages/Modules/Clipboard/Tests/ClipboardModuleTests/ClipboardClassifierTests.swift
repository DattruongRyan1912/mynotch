import AppKit
import CryptoKit
import Foundation
import Testing
@testable import ClipboardModule

@Suite struct ClipboardClassifierTests {
    let classifier = ClipboardClassifier(ignoreSensitive: true, colorsWithoutHash: true)

    /// A 2×3 RGBA bitmap built in code, so tests never depend on the system pasteboard.
    static let bitmap = NSBitmapImageRep(
        bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 3, bitsPerSample: 8, samplesPerPixel: 4,
        hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
    )!
    static let png = bitmap.representation(using: .png, properties: [:])!
    static let tiff = bitmap.tiffRepresentation!

    static func sha256(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    func text(_ string: String, rtf: Data? = nil) -> PasteboardSnapshot {
        PasteboardSnapshot(types: ["public.utf8-plain-text"], string: string, rtf: rtf)
    }

    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
    func sensitiveBeatsEverything(type: String) {
        let snapshot = PasteboardSnapshot(
            types: [type, ClipboardClassifier.ownWriteType, "public.file-url", "public.png", "public.utf8-plain-text"],
            string: "hunter2", png: Self.png, fileURLs: [URL(fileURLWithPath: "/tmp/a.txt")]
        )
        #expect(classifier.classify(snapshot) == .skipped(.sensitive))
    }

    @Test func sensitiveContentIsKeptWhenIgnoreSensitiveIsOff() {
        let classifier = ClipboardClassifier(ignoreSensitive: false, colorsWithoutHash: true)
        let snapshot = PasteboardSnapshot(types: ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"], string: "hunter2")
        #expect(classifier.classify(snapshot) == .content(.text("hunter2"), imageData: nil))
    }

    @Test func ownWriteIsSkippedBeforeFiles() {
        #expect(ClipboardClassifier.ownWriteType == "io.lucasvu.mynotch.clipboard")
        let snapshot = PasteboardSnapshot(
            types: [ClipboardClassifier.ownWriteType, "public.file-url"],
            string: "a.txt", fileURLs: [URL(fileURLWithPath: "/tmp/a.txt")]
        )
        #expect(classifier.classify(snapshot) == .skipped(.ownWrite))
    }

    @Test func whitespaceOnlyTextIsEmpty() {
        #expect(classifier.classify(text("  \n\t ")) == .skipped(.empty))
        #expect(classifier.classify(PasteboardSnapshot()) == .skipped(.empty))
    }

    @Test func unknownTypesAreUnsupported() {
        #expect(classifier.classify(PasteboardSnapshot(types: ["com.example.custom"])) == .skipped(.unsupported))
    }

    @Test func textOverTwoMegabytesOfUTF8IsTooLarge() {
        let limit = 2 * 1024 * 1024
        #expect(classifier.classify(text(String(repeating: "a", count: limit))) == .content(.text(String(repeating: "a", count: limit)), imageData: nil))
        #expect(classifier.classify(text(String(repeating: "a", count: limit + 1))) == .skipped(.tooLarge))
        // "é" is two UTF-8 bytes: fewer characters than the limit, more bytes.
        #expect(classifier.classify(text(String(repeating: "é", count: limit / 2 + 1))) == .skipped(.tooLarge))
    }

    @Test func filesBeatImageAndText() {
        let files = [URL(fileURLWithPath: "/tmp/a.txt"), URL(fileURLWithPath: "/tmp/b c.pdf")]
        let snapshot = PasteboardSnapshot(
            types: ["public.file-url", "public.png", "public.utf8-plain-text"],
            string: "a.txt", png: Self.png, fileURLs: files
        )
        #expect(classifier.classify(snapshot) == .content(.files(files), imageData: nil))
    }

    @Test func imageBeatsText() {
        let snapshot = PasteboardSnapshot(types: ["public.png", "public.utf8-plain-text"], string: "caption", png: Self.png)
        let image = ClipboardImage(fileName: Self.sha256(Self.png) + ".png", pixelWidth: 2, pixelHeight: 3, byteCount: Self.png.count)
        #expect(classifier.classify(snapshot) == .content(.image(image), imageData: Self.png))
    }

    @Test func tiffIsConvertedToPNG() throws {
        let result = classifier.classify(PasteboardSnapshot(types: ["public.tiff"], tiff: Self.tiff))
        guard case .content(.image(let image), let imageData?) = result else {
            Issue.record("Expected an image, got \(result)")
            return
        }
        #expect(imageData.starts(with: [0x89, 0x50, 0x4E, 0x47]))
        let decoded = try #require(NSBitmapImageRep(data: imageData))
        #expect(decoded.pixelsWide == 2 && decoded.pixelsHigh == 3)
        #expect(image == ClipboardImage(fileName: Self.sha256(imageData) + ".png", pixelWidth: 2, pixelHeight: 3, byteCount: imageData.count))
    }

    @Test func undecodableImageIsUnsupported() {
        let snapshot = PasteboardSnapshot(types: ["public.png"], png: Data("not an image".utf8))
        #expect(classifier.classify(snapshot) == .skipped(.unsupported))
    }

    @Test func undecodableImageFallsThroughToText() {
        let snapshot = PasteboardSnapshot(types: ["public.png", "public.utf8-plain-text"], string: "caption", png: Data("not an image".utf8))
        #expect(classifier.classify(snapshot) == .content(.text("caption"), imageData: nil))
    }

    @Test(arguments: [
        ("  https://example.com/a?b=1\n", "https://example.com/a?b=1"),
        ("http://example.com", "http://example.com"),
        ("mailto:me@example.com", "mailto:me@example.com"),
        ("HTTPS://EXAMPLE.COM", "HTTPS://EXAMPLE.COM"),
    ])
    func linkIsATrimmedHTTPOrMailtoURL(input: String, expected: String) {
        #expect(classifier.classify(text(input)) == .content(.link(URL(string: expected)!), imageData: nil))
    }

    @Test(arguments: ["ftp://example.com", "example.com", "https://example.com and more", "see https://example.com"])
    func otherStringsAreNotLinks(input: String) {
        #expect(classifier.classify(text(input)) == .content(.text(input), imageData: nil))
    }

    @Test func publicURLWithoutStringIsALink() {
        let url = URL(string: "https://example.com/page")!
        #expect(classifier.classify(PasteboardSnapshot(types: ["public.url"], url: url)) == .content(.link(url), imageData: nil))
    }

    @Test(arguments: [
        ("#ff8800", "#FF8800"),
        ("#FF880080", "#FF880080"),
        (" #fff ", "#FFFFFF"),
        ("#a1B", "#AA11BB"),
        ("ff8800", "#FF8800"),
        ("ff880080", "#FF880080"),
    ])
    func colorsAreNormalized(input: String, hex: String) {
        #expect(classifier.classify(text(input)) == .content(.color(hex: hex), imageData: nil))
    }

    @Test func colorsWithoutHashCanBeTurnedOff() {
        let classifier = ClipboardClassifier(ignoreSensitive: true, colorsWithoutHash: false)
        #expect(classifier.classify(text("ff8800")) == .content(.text("ff8800"), imageData: nil))
        #expect(classifier.classify(text("#ff8800")) == .content(.color(hex: "#FF8800"), imageData: nil))
    }

    @Test(arguments: ["#ff88", "#gggggg", "fff", "#ff88000", "ff88 00", "＃ff8800", "ｆｆ8800"])
    func otherStringsAreNotColors(input: String) {
        #expect(classifier.classify(text(input)) == .content(.text(input), imageData: nil))
    }

    @Test func textWithRTFIsRichText() {
        let rtf = Data("{\\rtf1 Hello}".utf8)
        #expect(classifier.classify(text("Hello", rtf: rtf)) == .content(.richText(plain: "Hello", rtf: rtf), imageData: nil))
    }

    @Test func linksAndColorsBeatRichText() {
        let rtf = Data("{\\rtf1 x}".utf8)
        #expect(classifier.classify(text("https://example.com", rtf: rtf)) == .content(.link(URL(string: "https://example.com")!), imageData: nil))
        #expect(classifier.classify(text("#FFF", rtf: rtf)) == .content(.color(hex: "#FFFFFF"), imageData: nil))
    }

    @Test func plainTextIsKeptVerbatim() {
        #expect(classifier.classify(text("  Xin chào\nthế giới ")) == .content(.text("  Xin chào\nthế giới "), imageData: nil))
    }
}
