import AppKit

nonisolated enum ClassificationResult: Sendable, Equatable {
    /// `imageData` is the PNG to store for `.image`, nil otherwise.
    case content(ClipboardContent, imageData: Data?)
    case skipped(SkipReason)
}

nonisolated enum SkipReason: Sendable, Equatable {
    case sensitive, ownWrite, empty, tooLarge, unsupported
}

/// Decides what a pasteboard snapshot becomes in history. Pure, so every rule is testable without a pasteboard.
nonisolated struct ClipboardClassifier: Sendable {
    /// Marker MyNotch adds to everything it writes, so the monitor never records its own writes.
    static let ownWriteType = "io.lucasvu.mynotch.clipboard"
    /// nspasteboard.org markers that password managers and similar apps set on secrets.
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]
    /// Applies to the UTF-8 string and to its RTF; oversized RTF is dropped and the plain text kept.
    static let maxTextBytes = 2 * 1024 * 1024

    var ignoreSensitive: Bool
    var colorsWithoutHash: Bool

    /// Whether a password manager or similar marked the copy as a secret, whatever the user chose to keep in history.
    static func isSensitive(_ snapshot: PasteboardSnapshot) -> Bool {
        !Set(snapshot.types).isDisjoint(with: sensitiveTypes)
    }

    /// Rules in priority order: sensitive, own write, files, image, then text (link, color as hex or as an rgb()/hsl()
    /// function, rich text, plain text).
    func classify(_ snapshot: PasteboardSnapshot) -> ClassificationResult {
        let types = Set(snapshot.types)
        if ignoreSensitive, Self.isSensitive(snapshot) { return .skipped(.sensitive) }
        if types.contains(Self.ownWriteType) { return .skipped(.ownWrite) }
        if !snapshot.fileURLs.isEmpty { return .content(.files(snapshot.fileURLs), imageData: nil) }
        if let image = Self.imageContent(snapshot) { return image }
        // Undecodable image data falls through: usable text is still captured, otherwise it is unsupported.
        return classifyText(snapshot)
    }

    private func classifyText(_ snapshot: PasteboardSnapshot) -> ClassificationResult {
        guard let string = snapshot.string else {
            if let url = snapshot.url { return .content(.link(url), imageData: nil) }
            return .skipped(snapshot.types.isEmpty ? .empty : .unsupported)
        }
        if string.utf8.count > Self.maxTextBytes { return .skipped(.tooLarge) }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty { return .skipped(.empty) }
        if let url = Self.link(trimmed) { return .content(.link(url), imageData: nil) }
        if let hex = colorHex(trimmed) { return .content(.color(hex: hex), imageData: nil) }
        if let hex = ClipboardCSSColor.hex(trimmed) { return .content(.color(hex: hex, original: trimmed), imageData: nil) }
        if let rtf = snapshot.rtf, rtf.count <= Self.maxTextBytes { return .content(.richText(plain: string, rtf: rtf), imageData: nil) }
        return .content(.text(string), imageData: nil)
    }

    /// Prefers the PNG as copied; TIFF (e.g. from screenshots or Preview) is converted so every stored image is PNG.
    private static func imageContent(_ snapshot: PasteboardSnapshot) -> ClassificationResult? {
        let bitmap: NSBitmapImageRep
        let png: Data
        if let data = snapshot.png, let decoded = NSBitmapImageRep(data: data) {
            bitmap = decoded
            png = data
        } else if let data = snapshot.tiff, let decoded = NSBitmapImageRep(data: data),
                  let converted = decoded.representation(using: .png, properties: [:]) {
            bitmap = decoded
            png = converted
        } else {
            return nil
        }
        let image = ClipboardImage(
            fileName: png.sha256Hex + ".png", pixelWidth: bitmap.pixelsWide, pixelHeight: bitmap.pixelsHigh, byteCount: png.count
        )
        return .content(.image(image), imageData: png)
    }

    /// One http/https URL with a host, or a mailto: with an address; anything else stays text.
    static func link(_ trimmed: String) -> URL? {
        guard !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed) else { return nil }
        let isComplete = switch url.scheme?.lowercased() {
        case "http", "https": url.host()?.isEmpty == false
        case "mailto": !url.path().isEmpty
        default: false
        }
        return isComplete ? url : nil
    }

    /// "#RGB", "#RRGGBB" or "#RRGGBBAA". Without "#" (only when `colorsWithoutHash` is on) it must be 6 or 8 hex
    /// digits mixing at least one digit and one letter A–F, so numbers like codes or dates and words like "facade" stay text.
    private func colorHex(_ trimmed: String) -> String? {
        let hasHash = trimmed.hasPrefix("#")
        var digits = hasHash ? String(trimmed.dropFirst()) : trimmed
        guard digits.allSatisfy({ $0.isASCII && $0.isHexDigit }) else { return nil }
        if !hasHash {
            guard colorsWithoutHash, digits.contains(where: \.isNumber), digits.contains(where: \.isLetter) else { return nil }
        }
        if hasHash, digits.count == 3 { digits = digits.map { "\($0)\($0)" }.joined() }
        guard digits.count == 6 || digits.count == 8 else { return nil }
        return "#" + digits.uppercased()
    }
}
